const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("bayloobAPI", {
  onSessions: cb => ipcRenderer.on("sessions", (_e, list) => cb(list)),
  onMusic: cb => ipcRenderer.on("music", (_e, np) => cb(np)),
  setPillRect: r => ipcRenderer.send("pill-rect", r),
  setMouseOver: over => ipcRenderer.send("mouse-over-ui", over),
  decide: (permId, decision) => ipcRenderer.send("decide", permId, decision),
  alwaysAllow: permId => ipcRenderer.send("always-allow", permId),
  answer: (permId, answers) => ipcRenderer.send("answer", permId, answers),
  focus: sessionId => ipcRenderer.invoke("focus", sessionId),
  music: action => ipcRenderer.send("music", action),
  openLauncher: () => ipcRenderer.send("open-launcher"),
  openPrompt: (sessionId, text) => ipcRenderer.send("open-prompt", sessionId, text),
  sendPrompt: (sessionId, text) => ipcRenderer.invoke("launcher:send-prompt", sessionId, text),
  keyboard: on => ipcRenderer.send("overlay-keyboard", on),
  setFull: on => ipcRenderer.send("overlay-full", on),
  voiceStatus: () => ipcRenderer.invoke("voice-status"),
  transcribe: audio => ipcRenderer.invoke("voice-transcribe", audio),
  voicePrompt: (sessionId, text) => ipcRenderer.send("voice-prompt", sessionId, text),
  stopSession: sessionId => ipcRenderer.send("stop-session", sessionId),
  togglePanel: () => ipcRenderer.send("toggle-panel"),
  toggleSounds: () => ipcRenderer.send("toggle-sounds"),
  openSettings: () => ipcRenderer.send("open-settings"),
  onHealth: cb => ipcRenderer.on("health", (_e, health) => cb(health)),
  onOutput: cb => ipcRenderer.on("output", (_e, lines) => cb(lines)),
  onDiffs: cb => ipcRenderer.on("diffs", (_e, diffs) => cb(diffs)),
  onTokens: cb => ipcRenderer.on("tokens", (_e, tokens) => cb(tokens)),
  onQueues: cb => ipcRenderer.on("queues", (_e, counts) => cb(counts)),
  onUsage: cb => ipcRenderer.on("usage", (_e, usage) => cb(usage)),
  onBlocked: cb => ipcRenderer.on("blocked", (_e, info) => cb(info)),
  onReceipts: cb => ipcRenderer.on("receipts", (_e, receipts) => cb(receipts)),
  onProgress: cb => ipcRenderer.on("progress", (_e, progress) => cb(progress)),
  onCollisions: cb => ipcRenderer.on("collisions", (_e, collisions) => cb(collisions)),
  onSoundConfig: cb => ipcRenderer.on("sound-config", (_e, config) => cb(config)),
  onRuleAllowed: cb => ipcRenderer.on("rule-allowed", (_e, info) => cb(info)),
  onErrorCopied: cb => ipcRenderer.on("error-copied", (_e, info) => cb(info)),
  fixError: sessionId => ipcRenderer.send("fix-error", sessionId),
  askTests: sessionId => ipcRenderer.send("ask-tests", sessionId),
  challenge: sessionId => ipcRenderer.invoke("challenge", sessionId),
  openFinding: (sessionId, file, line) => ipcRenderer.invoke("open-finding", sessionId, file, line),
  answerMenu: (sessionId, index) => ipcRenderer.invoke("answer-menu", sessionId, index),
  cancelHandoff: sessionId => ipcRenderer.send("cancel-handoff", sessionId),
});
